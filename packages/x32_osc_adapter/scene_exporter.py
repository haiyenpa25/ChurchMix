"""
Behringer X32 Native Scene (.scn) File Generator.
Exports snapshot parameters into standard Behringer X32 / M32 ASCII Scene file format
for loading directly via USB flash drive on the physical console front panel.
"""
from typing import Dict, Any, Optional
import time
from packages.x32_osc_adapter.client import Snapshot
from packages.eq_optimizer.recommender import x32_to_freq, x32_to_gain, x32_to_q


class SceneExporter:
    """Exports X32 snapshot to physical console .scn format."""

    @staticmethod
    def export_scn(snapshot: Snapshot, scene_name: str = "ChurchMix_Sunday") -> str:
        """
        Generate .scn text content compatible with X32/M32 firmware v4.xx.
        Format header: #2.1# "SceneName" "" %000000000 1
        """
        clean_name = scene_name.replace('"', '').strip()[:20]
        lines = [
            f'#2.1# "{clean_name}" "ChurchMix Calibrated Scene" %000000000 1',
        ]

        # 1. Export 32 channels
        for ch in range(1, 33):
            ch_str = f"/ch/{ch:02d}"
            name = snapshot.parameters.get(f"{ch_str}/config/name", f"Ch {ch}")
            color = snapshot.parameters.get(f"{ch_str}/config/color", 1)
            src = snapshot.parameters.get(f"{ch_str}/config/source", ch - 1)
            fader = snapshot.parameters.get(f"{ch_str}/mix/fader", 0.75)
            on = snapshot.parameters.get(f"{ch_str}/mix/on", 1)
            lr = snapshot.parameters.get(f"{ch_str}/mix/lr", 1 if ch != 11 else 0) # Enforce DL16 #11 invariant
            hpon = snapshot.parameters.get(f"{ch_str}/preamp/hpon", 1 if ch == 1 else 0)
            hpf = snapshot.parameters.get(f"{ch_str}/preamp/hpf", 0.2)

            lines.append(f'{ch_str}/config "{name}" {color} YE {src}')
            lines.append(f'{ch_str}/preamp +0.0 OFF {"ON" if hpon else "OFF"} {x32_to_freq(hpf):.1f}')
            lines.append(f'{ch_str}/mix/fader {fader:.4f}')
            lines.append(f'{ch_str}/mix/on {"ON" if on else "OFF"}')
            lines.append(f'{ch_str}/mix/lr {"ON" if lr else "OFF"}')

            # Export EQ bands
            eq_on = snapshot.parameters.get(f"{ch_str}/eq/on", 1)
            lines.append(f'{ch_str}/eq {"ON" if eq_on else "OFF"}')
            for band in range(1, 5):
                f_val = snapshot.parameters.get(f"{ch_str}/eq/{band}/f", 0.5)
                g_val = snapshot.parameters.get(f"{ch_str}/eq/{band}/g", 0.5)
                q_val = snapshot.parameters.get(f"{ch_str}/eq/{band}/q", 0.5)
                freq = x32_to_freq(f_val)
                gain = x32_to_gain(g_val)
                q = x32_to_q(q_val)
                lines.append(f'{ch_str}/eq/{band} PEQ {freq:.1f} {gain:+.1f} {q:.2f}')

        # 2. Export Hard Invariant Protection for DL16 In 11
        lines.append('/outputs/p16/11/src 11')
        lines.append('/outputs/p16/11/tap "Direct Pre"')
        lines.append('/ch/11/mix/lr OFF')

        # 3. Footer metadata
        lines.append(f'# Generated by X32 AI Sound Engineer at {time.strftime("%Y-%m-%d %H:%M:%S")}')
        lines.append(f'# Snapshot SHA-256: {snapshot.sha256}')

        return "\n".join(lines)
